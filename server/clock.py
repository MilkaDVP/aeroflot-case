"""
Единое обращение со временем.

Правило одно: в базе всё время хранится в UTC, наружу отдаётся с явным
указанием часового пояса.

Зачем так строго. Сервер в контейнере живёт по UTC, а браузер диспетчера —
по местному времени. Если отдать строку «2026-09-03T06:36:00» без пояса,
браузер прочитает её как местное время и покажет вызов, поступивший минуту
назад, случившимся несколько часов назад. Для диспетчерской системы, где
по времени поступления вызова считается соблюдение регламента, это
не косметика, а искажение рабочих данных.
"""

from datetime import datetime, timezone


def utc_now():
    """
    Текущий момент в UTC, без сведений о поясе.

    Пояс снимается намеренно: SQLite хранит дату строкой и не различает
    aware- и naive-значения, поэтому смешивать их в одной колонке нельзя.
    Договорённость простая — в базе всегда UTC.
    """
    return datetime.now(timezone.utc).replace(tzinfo=None)


def to_iso_utc(value):
    """
    Момент из базы в строку ISO с явным поясом UTC.

    Именно суффикс пояса позволяет браузеру перевести время в местное.
    """
    if value is None:
        return None
    return value.replace(tzinfo=timezone.utc).isoformat()


def utc_today():
    """Текущая дата по UTC — для проверки сроков действия отметок."""
    return utc_now().date()
