# --- Регламент ПАО «Аэрофлот» ----------------------------------------------

# Предельное время прибытия сотрудника к воздушному судну с момента вызова.
# Кандидаты с большим временем в пути отсеиваются алгоритмом подбора.
REGULATION_ARRIVAL_LIMIT_MIN = 15

# Порог «жёлтой зоны»: кандидат укладывается в регламент, но запаса почти нет.
# Используется только для окраски интерфейса, на подбор не влияет.
