SUGGESTION_TIMEOUT_S = 10

# --- Контроль регламента в реальном времени --------------------------------
#
# Пятнадцать минут — договорное условие со штрафами, и даже небольшое
# опоздание стоит денег. Поэтому время прибытия контролируется не только
# в момент назначения, а всё время, пока исполнитель в пути: прогноз
# пересчитывается по его текущим координатам, и диспетчер получает
# красное уведомление, как только становится видно, что срок будет сорван.

# Запас до контрольного срока, меньше которого прогноз считается «впритык».
# Жёлтый сигнал: вмешиваться ещё рано, но смотреть уже пора.
DEADLINE_MARGIN_MIN = 2

# Через сколько минут после поступления вызов без исполнителя становится
# тревогой. Даже лучшему кандидату нужно несколько минут на дорогу,
# и если за это время никого не назначили, регламент уже под угрозой.
UNASSIGNED_ALERT_AFTER_MIN = 3

# Возраст GPS-фиксации, после которого прогноз по ней ненадёжен. GPS на
# перроне теряет сигнал у зданий и под крыльями, и прогноз по старой
# точке молча показывал бы «успевает» человеку, который давно стоит.
POSITION_STALE_S = 90

# Телефон, не выходящий на связь дольше этого, считается без связи:
# это другая беда, чем потеря GPS, и диспетчеру важно их различать.
DEVICE_SILENT_S = 60

# Источники координат. Устаревать может только настоящий GPS: точку,
# поставленную вручную (имитация в приложении, перестановка на карте
# диспетчером), не обновляют намеренно — и тревога «нет сигнала» по ней
# была бы ложной.
LOCATION_GPS = "gps"
LOCATION_SIMULATION = "simulation"
LOCATION_MANUAL = "manual"
LOCATION_SOURCES = (LOCATION_GPS, LOCATION_SIMULATION, LOCATION_MANUAL)

# Ближе этого к машине парка инженер считается севшим в неё. Без этого
# машина числилась «ждущей» до самого прибытия к борту, и прогноз
# заставлял человека, уже едущего на ней, возвращаться к месту стоянки.
PICKUP_RADIUS_M = 40

# --- Наставник: разбор действий диспетчера ----------------------------------

# Переопределение решения системы, которое стоит меньше этого, потерей
# не считается: минута разницы — в пределах точности оценки времени в пути.
OVERRIDE_TOLERANCE_MIN = 1

# За какое время назад собирается лента и итог смены. Смена длится 12 часов.
