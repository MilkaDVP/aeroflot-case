/**
 * Атрибуты подсказки для термина: ` title="…" data-term="…"`.
 * Подставляется прямо в разметку рядом с классом элемента.
 */
function term(key) {
  const entry = TERMS[key];
  if (!entry) {
    return "";
  }
  return ` title="${escapeHtml(entry.name)}. ${escapeHtml(entry.text)}" data-term="${key}"`;
}
